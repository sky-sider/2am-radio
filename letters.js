function chapter3LetterBody(id,beat){
 if(beat==='side')return '';
 const base=CH3_BEATS[id]?.[beat]||'';
 let intro='';
 if(beat==='start'&&CH3_ROUTE_LINES[id]){
  const route=chapter2Route(id);
  intro=CH3_ROUTE_LINES[id]?.[route]||'';
 }
 // 第3章中の決断は、本人が実際に行動した夜の後から語られる。
 const after=s.chapter3?.decisions?.[id];
 const offset=chapter3Offset(s.night);
 const decisionNight=s.chapter3?.decisionNights?.[id];
 const extra=(after&&offset>=0&&s.night>decisionNight&&['after','end'].includes(beat))?CH3_DECISION_TEXT[id]?.[after]?.[1]:null;
 return [intro,base,extra].filter(Boolean).join('\n\n');
}
